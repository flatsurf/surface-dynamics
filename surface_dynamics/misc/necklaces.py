r"""
Necklaces and Lyndon words of bounded weight.

A *necklace* is a word that is least, in the lexicographic order, among its
rotations; a *Lyndon word* is an aperiodic necklace, that is a word strictly
less than all its other rotations. The function :func:`weighted_necklaces`
iterates over the necklaces (or the Lyndon words) over an alphabet of
weighted letters, whose weight lies in a given range. Optionally it keeps
only the words whose letters cover a set of bits, and computes along the
words a product of elements attached to the letters.

See [FreMai78]_, [FreKes86]_ and [CatRusSawSerMie00]_ for the algorithm.

EXAMPLES::

    sage: from surface_dynamics.misc.necklaces import weighted_necklaces
    sage: list(weighted_necklaces([1, 1], 3, primitive=True))
    [(0,), (0, 0, 1), (0, 1), (0, 1, 1), (1,)]
"""
